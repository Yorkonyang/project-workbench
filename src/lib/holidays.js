// 周末 / 节假日 的淡灰底色（半透明，置于行底色之下作为最底层，不遮挡项目色带/行色）
export const OFF_DAY_BG = 'rgba(148, 163, 184, 0.18)'; // slate-400 @ 18%，再浅一档

/**
 * 将任意颜色（#hex / #rgb / rgb() / rgba()）转为带透明度的 rgba 字符串。
 * 用于把「项目色带/行底色」在周末/节假日半透明化，让最底层的灰底透出（既不遮挡色带、又能指示休息日）。
 */
export function withAlpha(color, alpha) {
  if (!color) return `rgba(148, 163, 184, ${alpha})`;
  const c = String(color).trim();
  let r, g, b;
  if (c.startsWith('#')) {
    const h = c.slice(1);
    const full = h.length === 3 ? h.split('').map((x) => x + x).join('') : h;
    const n = parseInt(full, 16);
    r = (n >> 16) & 255;
    g = (n >> 8) & 255;
    b = n & 255;
  } else if (c.startsWith('rgb')) {
    const m = c.match(/\d+/g);
    if (!m || m.length < 3) return color;
    [r, g, b] = m.slice(0, 3).map(Number);
  } else {
    return color; // 无法解析则原样返回
  }
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

const holidaySet = new Set(HOLIDAYS);
const makeupSet = new Set(MAKEUP_WORKDAYS);

/**
 * 返回某天在「工作日历」中的类型：
 * - 'makeup'   倒休工作日 / 补班（原本周末但需上班）→ 与正常工作日同底色
 * - 'holiday'  法定节假日（含调休连休）→ 淡灰底色
 * - 'weekend'  周六 / 周日 → 淡灰底色
 * - 'workday'  正常工作日 → 无特殊底色
 * @param {Date|string} date Date 对象或 'yyyy-MM-dd' 字符串
 */
export function getDayType(date) {
  const d = date instanceof Date ? date : parseISO(date);
  const iso = format(d, 'yyyy-MM-dd');
  // 补班日优先级最高：覆盖周末判断
  if (makeupSet.has(iso)) return 'makeup';
  if (holidaySet.has(iso)) return 'holiday';
  const dow = d.getDay(); // 0=周日, 6=周六
  if (dow === 0 || dow === 6) return 'weekend';
  return 'workday';
}

// 是否为「淡灰底色」日期（周末 或 法定节假日）
export function isOffDay(date) {
  const t = getDayType(date);
  return t === 'weekend' || t === 'holiday';
}
